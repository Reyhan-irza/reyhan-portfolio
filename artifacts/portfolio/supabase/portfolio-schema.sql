-- Portfolio database contract for Supabase
-- Safe to run repeatedly: existing tables and rows are not dropped or reset.
--
-- Existing public data tables used by the app:
--   comments(id, username, message, pinned, created_at)
--   replies(id, comment_id, reply_text, admin_name, created_at)
--   news(id, title, thumbnail, category, content, published, created_at)
--   visitors(id, created_at, user_agent)
--
-- The app also queries public.admins(id, username, password) directly from the
-- browser. This script intentionally does not create or change that table or
-- its policies: granting anon access to that query exposes stored passwords.
-- Migrate that legacy login separately before creating a fresh admin schema.

begin;

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  username varchar(50) not null check (char_length(btrim(username)) between 1 and 50),
  message varchar(500) not null check (char_length(btrim(message)) between 1 and 500),
  pinned boolean not null default false,
  created_at timestamptz not null default now()
);

-- Public visitors may submit a comment, but cannot edit or delete comments.
-- Existing SELECT and admin policies are left untouched.
grant insert on table public.comments to anon;

do $comments_policy$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'comments'
      and policyname = 'comments_anon_insert_validated'
  ) then
    create policy comments_anon_insert_validated
      on public.comments
      for insert
      to anon
      with check (
        username is not null
        and char_length(btrim(username)) between 1 and 50
        and message is not null
        and char_length(btrim(message)) between 1 and 500
      );
  end if;
end
$comments_policy$;

create table if not exists public.replies (
  id bigint generated by default as identity primary key,
  comment_id bigint not null references public.comments(id) on delete cascade,
  reply_text text not null check (char_length(btrim(reply_text)) > 0),
  admin_name text not null default 'Developer',
  created_at timestamptz not null default now()
);

create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) > 0),
  thumbnail text not null default '',
  category text not null default 'General',
  content text not null check (char_length(btrim(content)) > 0),
  published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.visitors (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_agent varchar(200)
);

create index if not exists replies_comment_id_created_at_idx
  on public.replies (comment_id, created_at asc);
create index if not exists comments_created_at_idx
  on public.comments (created_at desc);
create index if not exists news_published_created_at_idx
  on public.news (published, created_at desc);
create index if not exists visitors_created_at_idx
  on public.visitors (created_at desc);

-- One rating per browser-generated UUID. The UUID is not personal information;
-- it is stored in that browser's localStorage so a visitor can change their vote.
create table if not exists public.portfolio_ratings (
  visitor_id uuid primary key,
  rating smallint not null check (rating between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.portfolio_ratings enable row level security;
revoke all on table public.portfolio_ratings from public, anon, authenticated;

-- Return aggregate data only; never expose individual visitor IDs or votes.
create or replace view public.portfolio_rating_summary
with (security_invoker = false) as
select
  count(*)::integer as rating_count,
  coalesce(round(avg(rating)::numeric, 2), 0.00::numeric) as average_rating,
  count(*) filter (where rating = 1)::integer as one_star_count,
  count(*) filter (where rating = 2)::integer as two_star_count,
  count(*) filter (where rating = 3)::integer as three_star_count,
  count(*) filter (where rating = 4)::integer as four_star_count,
  count(*) filter (where rating = 5)::integer as five_star_count
from public.portfolio_ratings;

revoke all on public.portfolio_rating_summary from public;
grant select on public.portfolio_rating_summary to anon, authenticated;

-- Writes are routed through this validated function. An anonymous client can
-- submit/change its own browser UUID's vote, but cannot read or delete votes.
create or replace function public.submit_portfolio_rating(
  p_visitor_id uuid,
  p_rating smallint
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if p_visitor_id is null then
    raise exception 'A visitor ID is required' using errcode = '22023';
  end if;
  if p_rating is null or p_rating not between 1 and 5 then
    raise exception 'Rating must be between 1 and 5' using errcode = '22023';
  end if;

  insert into public.portfolio_ratings (visitor_id, rating)
  values (p_visitor_id, p_rating)
  on conflict (visitor_id) do update
    set rating = excluded.rating,
        updated_at = now();
end;
$$;

revoke all on function public.submit_portfolio_rating(uuid, smallint) from public;
grant execute on function public.submit_portfolio_rating(uuid, smallint) to anon, authenticated;

comment on table public.portfolio_ratings is
  'One current 1–5 star portfolio rating per browser-generated visitor UUID.';
comment on view public.portfolio_rating_summary is
  'Public aggregate only; individual ratings and visitor UUIDs remain private.';

commit;
